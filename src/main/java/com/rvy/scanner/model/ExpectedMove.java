package com.rvy.scanner.model;

public class ExpectedMove {

    private Double straddle;
    private Double implied;
    private Double used;

    public Double getStraddle() {
        return straddle;
    }

    public void setStraddle(Double straddle) {
        this.straddle = straddle;
    }

    public Double getImplied() {
        return implied;
    }

    public void setImplied(Double implied) {
        this.implied = implied;
    }

    public Double getUsed() {
        return used;
    }

    public void setUsed(Double used) {
        this.used = used;
    }
}
